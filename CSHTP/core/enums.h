// 日志类型（类图：日志类型）
//
// 设计口径：只记「事情已经办成、以后可能要追责或复核」的结果，不记过程
//   （提交、撤回、取消、浏览都不记）。结果在日志内容里用文字区分，
//   所以「通过」和「驳回」共用同一个类型：
//
//     Register          用户注册成功
//     ItemSold          商品成交（卖家确认预约、生成交易记录的那一刻）
//     ItemAudited       商品审核有了结论（通过或驳回，内容里写结果）
//     SellerAudited     卖家身份认证有了结论（内容里写结果）
//
// 【2026-11-08 调整】原来有 14 种，覆盖提交审核、撤回、取消预约、封禁等。
//   本实验是本地控制台程序，日志只用于事后查「谁在什么时候把哪条数据
//   改成了什么」，学生规模的测试数据里，过程类日志没有查询价值，反而要
//   在每个业务函数里埋点。于是砍到 4 种结果类动作。
//   代价：REQ-015（违规下架）、REQ-016（封禁）、REQ-028（越权拦截）要求的
//   「须记录日志」不再有对应记录，报告里要写明这项简化。
enum class LogType {
    Register,               // 注册成功
    ItemSold,               // 商品成交
    ItemAudited,            // 商品审核有结论
    SellerAudited           // 卖家身份认证有结论
};
